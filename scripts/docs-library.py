"""Index, check and export the portable dev_fram documentation library."""

import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import sys
from urllib.parse import unquote
import zipfile


ROOT = Path(__file__).resolve().parents[1]
START = "<!-- DOCS_INDEX_START -->"
END = "<!-- DOCS_INDEX_END -->"
METADATA = "scripts/docs-metadata.json"
SOURCES = "scripts/docs-sources.json"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def document_digest(path):
    data = path.read_bytes()
    if path.suffix.lower() in {".md", ".py", ".ps1", ".json"}:
        text = data.decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")
        data = text.encode("utf-8")
    return digest(data)


def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n",
                    encoding="utf-8")


def local_path(relative):
    path = PurePosixPath(relative)
    if path.is_absolute() or ".." in path.parts or "\\" in relative or ":" in relative:
        raise ValueError("unsafe library path: " + relative)
    resolved = (ROOT / relative).resolve()
    if not resolved.is_relative_to(ROOT.resolve()):
        raise ValueError("path leaves library: " + relative)
    return resolved


def inventory():
    paths = {"README.md", SOURCES, "scripts/docs-library.py"}
    for folder in ("docs", "rules"):
        paths.update(p.relative_to(ROOT).as_posix()
                     for p in (ROOT / folder).rglob("*") if p.is_file())
    paths.update(p.relative_to(ROOT).as_posix()
                 for p in (ROOT / "scripts").iterdir()
                 if p.is_file() and p.suffix in (".ps1", ".py", ".json")
                 and p.name != "docs-metadata.json")
    if (ROOT / "tests/docs_library_test.py").is_file():
        paths.add("tests/docs_library_test.py")
    return sorted(paths)


def sources_check(manifest, paths):
    if manifest.get("schema_version") != 1:
        raise ValueError("unsupported source manifest version")
    sources = manifest["sources"]
    ids = {item["id"] for item in sources}
    if len(ids) != len(sources):
        raise ValueError("duplicate source id")
    for item in sources:
        if not re.fullmatch(r"[0-9a-f]{40}", item["commit"]):
            raise ValueError("invalid source commit: " + item["id"])
        if not re.fullmatch(r"[0-9a-f]{64}", item["sha256"]):
            raise ValueError("invalid source hash: " + item["id"])
        local_path(item["path"])
    documents = manifest["documents"]
    targets = {item["path"] for item in documents}
    if len(targets) != len(documents):
        raise ValueError("duplicate document provenance")
    for item in documents:
        if item["path"] not in paths and item["path"] != "AGENTS.md":
            raise ValueError("provenance points to missing document: " + item["path"])
        if not item["source_ids"] or set(item["source_ids"]) - ids:
            raise ValueError("unresolved source: " + item["path"])
        if item["kind"] == "excerpt":
            text = local_path(item["path"]).read_text(encoding="utf-8")
            for fragment in item["fragments"]:
                match = re.search(
                    r"<!-- SOURCE_FRAGMENT " + re.escape(fragment["id"]) +
                    r" -->\n(.*?)<!-- END_SOURCE_FRAGMENT " +
                    re.escape(fragment["id"]) + r" -->", text, re.S)
                if not match or digest(match.group(1).encode()) != fragment["sha256"]:
                    raise ValueError("excerpt hash mismatch: " + item["path"])
    missing = {p for p in paths if p.startswith("docs/") and p.endswith(".md")} - targets
    if missing:
        raise ValueError("documentation inventory has missing provenance: " +
                         ", ".join(sorted(missing)))


def links_check(paths, documents):
    historical = {d["path"] for d in documents if d["kind"] == "excerpt"}
    for relative in paths:
        if not relative.endswith(".md") or relative in historical:
            continue
        text = local_path(relative).read_text(encoding="utf-8")
        text = re.sub(r"```.*?```", "", text, flags=re.S)
        for target in re.findall(r"\]\(([^)]+)\)", text):
            target = unquote(target.strip("<> ")).split("#", 1)[0]
            if not target or re.match(r"^[a-z]+://", target):
                continue
            resolved = (local_path(relative).parent / target).resolve()
            if not resolved.is_relative_to(ROOT.resolve()) or not resolved.exists():
                raise ValueError("broken link in " + relative + ": " + target)


def index_block(entries):
    lines = [START, "<!-- generated by scripts/docs-library.py; do not edit -->", "",
             "## Documentation Index", "",
             "Paths and hashes are relative to this framework checkout.", "",
             "| Path | Status | Kind | SHA-256 |",
             "| --- | --- | --- | --- |"]
    for item in entries:
        if item["path"].startswith("docs/"):
            lines.append("| {path} | {status} | {kind} | {sha256} |".format(**item))
    return "\n".join(lines + ["", END])


def indexed_agents(entries):
    text = (ROOT / "AGENTS.md").read_text(encoding="utf-8")
    block = index_block(entries)
    if START not in text and END not in text:
        return text.rstrip() + "\n\n" + block + "\n"
    if text.count(START) != 1 or text.count(END) != 1:
        raise ValueError("invalid documentation index markers")
    start, end = text.index(START), text.index(END)
    if end <= start:
        raise ValueError("invalid documentation index order")
    return text[:start] + block + text[end + len(END):]


def validate_inputs():
    paths = inventory()
    manifest = json.loads(local_path(SOURCES).read_text(encoding="utf-8"))
    sources_check(manifest, paths)
    links_check(paths + ["AGENTS.md"], manifest["documents"])
    return paths, manifest


def update():
    paths, manifest = validate_inputs()
    documents = {d["path"]: d for d in manifest["documents"]}
    entries = []
    for path in paths:
        info = documents.get(path, {})
        entries.append({"path": path, "kind": info.get("kind", "tool-or-entry"),
                        "status": info.get("status", "active"),
                        "sha256": document_digest(local_path(path))})
    (ROOT / "AGENTS.md").write_text(indexed_agents(entries), encoding="utf-8", newline="\n")
    write_json(local_path(METADATA), {"schema_version": 1, "files": entries,
                                    "agents_sha256": document_digest(ROOT / "AGENTS.md")})
    print("[DOCS] Updated inventory and index for", len(entries), "files")


def check():
    paths, manifest = validate_inputs()
    metadata = json.loads(local_path(METADATA).read_text(encoding="utf-8"))
    entries = metadata["files"]
    registered = [item["path"] for item in entries]
    if len(set(registered)) != len(registered) or set(registered) != set(paths):
        raise ValueError("documentation inventory differs from registered files")
    for item in entries:
        if document_digest(local_path(item["path"])) != item["sha256"]:
            raise ValueError("hash mismatch: " + item["path"])
    if document_digest(ROOT / "AGENTS.md") != metadata["agents_sha256"]:
        raise ValueError("hash mismatch: agent instructions AGENTS.md")
    if (ROOT / "AGENTS.md").read_text(encoding="utf-8") != indexed_agents(entries):
        raise ValueError("documentation index is stale")
    print("[DOCS] PASS:", len(entries), "files,", len(manifest["sources"]),
          "sources, provenance, excerpt hashes, links and index")
    return paths, manifest


def export(output):
    paths, manifest = check()
    output = Path(output).resolve()
    if output.is_relative_to(ROOT / "docs") or output.is_relative_to(ROOT / "rules"):
        raise ValueError("export output cannot be inside indexed documents")
    output.mkdir(parents=True, exist_ok=True)
    baseline = manifest["baseline"]
    archive = output / ("dev-fram-docs-" + baseline["date"] + "-" +
                        baseline["framework_commit"][:7] + ".zip")
    files = sorted(set(paths) | {"AGENTS.md", METADATA})
    payload = {path: local_path(path).read_bytes() for path in files}
    sums = "".join(digest(data) + "  " + path + "\n" for path, data in payload.items())
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as bundle:
        for path, data in payload.items():
            bundle.writestr(path, data)
        bundle.writestr("SHA256SUMS", sums.encode())
    archive.with_suffix(".zip.sha256").write_text(
        digest(archive.read_bytes()) + "  " + archive.name + "\n", encoding="ascii")
    verify_archive(archive)
    print("[DOCS] Exported", archive, "with", len(files), "library files")


def verify_archive(archive):
    with zipfile.ZipFile(archive) as bundle:
        names = bundle.namelist()
        if len(set(names)) != len(names):
            raise ValueError("duplicate archive entry")
        expected = {}
        for line in bundle.read("SHA256SUMS").decode().splitlines():
            value, name = line.split("  ", 1)
            if name in expected or not re.fullmatch(r"[0-9a-f]{64}", value):
                raise ValueError("invalid archive checksum entry")
            expected[name] = value
        if set(names) != set(expected) | {"SHA256SUMS"}:
            raise ValueError("archive inventory mismatch")
        for name, value in expected.items():
            local_path(name)
            if digest(bundle.read(name)) != value:
                raise ValueError("archive hash mismatch: " + name)
    print("[DOCS] PASS: archive inventory and all checksums")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("update")
    commands.add_parser("check")
    package = commands.add_parser("export")
    package.add_argument("--output", default=str(ROOT / "exports"))
    verify = commands.add_parser("verify-archive")
    verify.add_argument("archive")
    args = parser.parse_args()
    try:
        if args.command == "update":
            update()
        elif args.command == "check":
            check()
        elif args.command == "export":
            export(args.output)
        else:
            verify_archive(args.archive)
    except (ValueError, OSError, KeyError, zipfile.BadZipFile) as error:
        print("[DOCS] FAIL:", error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
